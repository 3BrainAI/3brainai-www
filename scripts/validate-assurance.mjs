import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const html=await readFile('assurance/index.html','utf8');
assert.match(html, /<title>Security, Governance &amp; Assurance \| 3BrainAI Nexus<\/title>/);
assert.match(html, /<link rel="canonical" href="https:\/\/www\.3brain\.ai\/assurance\/">/);
assert.match(html, /connect-src 'none'; form-action 'none'/);
assert.match(html, /<meta name="robots" content="index,follow">/);
assert.match(html, /Last reviewed: <time datetime="2026-09-15">15 September 2026<\/time>/);
assert.equal([...html.matchAll(/<h1\b/g)].length,1);
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(x=>x[1]);
assert.equal(new Set(ids).size,ids.length,'IDs must be unique');
for(const [,anchor] of html.matchAll(/href="#([^"]+)"/g))assert.ok(ids.includes(anchor),`Missing anchor ${anchor}`);
for(const [,label] of html.matchAll(/\bfor="([^"]+)"/g))assert.ok(ids.includes(label),`Missing labelled control ${label}`);
for(const [,recipient] of html.matchAll(/mailto:([^"?]+)/g))assert.equal(recipient,'contact@3brain.ai');
assert.match(html,/Company ID: 295 13 049/);
assert.match(html,/Korunní 2569\/108/);
assert.match(html,/controlled-case Proof of Concept validation/);
assert.match(html,/It does not submit a request, store your answers or grant access/);
assert.match(html,/<button[^>]+type="submit" disabled>/);
assert.match(html,/name="privacy" required/);
assert.doesNotMatch(html,/security@|assurance@|SOC 2|ISO 27001|DORA compliant|enterprise-grade|military-grade|3b-nexus-cri-assurance|RESTRICTED-TECHNICAL|TARGET-DESIGN|BUILD \/ TEST/);
const script=await readFile('assets/js/assurance-request.js','utf8');
assert.doesNotMatch(script,/\bfetch\s*\(|XMLHttpRequest|sendBeacon|localStorage|sessionStorage|innerHTML/);
const claims=[...html.matchAll(/data-assurance-claim="([^"]+)"/g)].map(x=>x[1]);
assert.equal(claims.length,15);
assert.equal(new Set(claims).size,claims.length);
console.log('Assurance: metadata, 15 claim identifiers, anchors, labels and local-only enquiry boundary checked.');
